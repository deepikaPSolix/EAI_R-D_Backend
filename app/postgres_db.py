from flask import current_app
import psycopg2
import json
import os
from psycopg2.extras import Json



class DatabaseManager:
    _instance = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(DatabaseManager, cls).__new__(cls)
        return cls._instance

    def __init__(self):
        # Prevent reinitialization on subsequent calls
        if hasattr(self, "_initialized") and self._initialized:
            return
        try:
            self.conn = psycopg2.connect(os.getenv("DSN_postgres"))
            self.conn.autocommit = True
            self.cur = self.conn.cursor()
            self.setup_tables()
            current_app.logger.info("Connected to the database and tables are set up.")
            self._initialized = True
        except Exception as e:
            current_app.logger.info("Error connecting to the database:", e)
            raise

