    def add_file_metadata(self, file_metadata_data):
        current_app.logger.info(f"Started add_file_metadata, {file_metadata_data}")
        file_id = file_metadata_data['file_id']
        file_name = file_metadata_data['file_name']
        file_type = file_metadata_data['file_type']
        creation_time = file_metadata_data['created_time']
        last_modification_time = file_metadata_data['last_modification_time']
        created_by = file_metadata_data['created_by']
        modified_by = file_metadata_data['modified_by']
        file_size = file_metadata_data['file_size']
        current_app.logger.info("Called the add_file_metadata")
        sql = """
        INSERT INTO public.file_metadata (
            file_id, file_name, file_type, creation_time, last_modification_time, created_by, modified_by, file_size
        ) VALUES (
            %s, %s, %s, NOW(), NOW(), %s, %s, %s
        )
        ON CONFLICT (file_name)
        DO UPDATE SET
            file_id                = EXCLUDED.file_id,
            file_type              = EXCLUDED.file_type,
            file_size              = EXCLUDED.file_size,
            last_modification_time = NOW(),
            modified_by            = EXCLUDED.modified_by;
        """
        try:
            with self.conn.cursor() as cur:
                cur.execute(sql, (file_id, file_name, file_type, created_by, modified_by, file_size))
                self.conn.commit()
            current_app.logger.info(f"File metadata '{file_id}' inserted/updated successfully.")
        except Exception as e:
            self.conn.rollback()
            current_app.logger.error("Error inserting file_metadata", exc_info=True)
            raise e

