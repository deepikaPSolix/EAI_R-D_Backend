    def add_file_evaluation(self, evaluation_data):
        current_app.logger.info(f"Started add_file_evaluation, data: {evaluation_data}")
        
        file_name = evaluation_data.get("file_name")
        if file_name is None:
            current_app.logger.warning("file_name is None; defaulting to 'unknown'")
            file_name = "unknown"
        else:
            file_name = file_name.strip()
        
        # These values may be None if the particular evaluation didn't calculate them.
        hallucination = evaluation_data.get("hallucination")
        relevance = evaluation_data.get("relevance")
        created_by = evaluation_data.get("created_by", "system")
        modified_by = evaluation_data.get("modified_by", "system")

        sql = """
        INSERT INTO public.file_evaluation (
            file_name, hallucination, relevance, creation_time, last_modification_time, created_by, modified_by
        ) VALUES (
            %s, %s, %s, NOW(), NOW(), %s, %s
        )
        ON CONFLICT (file_name) DO UPDATE SET
            hallucination = COALESCE(EXCLUDED.hallucination, public.file_evaluation.hallucination),
            relevance = COALESCE(EXCLUDED.relevance, public.file_evaluation.relevance),
            last_modification_time = NOW(),
            modified_by = EXCLUDED.modified_by;
        """
        
        try:
            with self.conn.cursor() as cur:
                cur.execute(sql, (file_name, hallucination, relevance, created_by, modified_by))
                self.conn.commit()
            current_app.logger.info(f"File evaluation for '{file_name}' inserted/updated successfully.")
        except Exception as e:
            self.conn.rollback()
            current_app.logger.error("Error inserting file_evaluation", exc_info=True)
            raise e




